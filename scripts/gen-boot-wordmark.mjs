#!/usr/bin/env node
// Bakes the boot screen's handwritten wordmark: lays out a word in the
// single-stroke EMS Allure font (SIL OFL, scripts/assets/EMSAllure.svg),
// smooths each polyline and writes public/boot-wordmark.js. Pre-baking keeps
// the boot screen free of font parsing on the critical path.
//
//   node scripts/gen-boot-wordmark.mjs [word]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const word = process.argv[2] ?? 'Aerial';
const svg = readFileSync(join(root, 'scripts/assets/EMSAllure.svg'), 'utf8');

const unitsPerEm = parseFloat(/units-per-em="([\d.]+)"/.exec(svg)[1]);
const defaultAdv = parseFloat(/<font[^>]*horiz-adv-x="([\d.]+)"/.exec(svg)[1]);
const glyphs = new Map();
for (const m of svg.matchAll(/<glyph\s+([^>]*?)\/?>/g)) {
  const attr = (n) => new RegExp(`${n}="([^"]*)"`).exec(m[1])?.[1];
  const u = attr('unicode');
  if (u == null) continue;
  const strokes = [];
  let cur = null;
  const tok = (attr('d') ?? '').match(/[ML]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  for (let i = 0; i < tok.length; ) {
    if (tok[i] === 'M' || tok[i] === 'L') {
      if (tok[i] === 'M') strokes.push((cur = []));
      i++;
      continue;
    }
    cur.push([parseFloat(tok[i]), parseFloat(tok[i + 1])]);
    i += 2;
  }
  glyphs.set(u, { adv: parseFloat(attr('horiz-adv-x') ?? defaultAdv), strokes });
}

/** Chaikin corner cutting, endpoints kept: turns the plotter polylines into curves. */
function chaikin(pts, rounds) {
  let p = pts;
  for (let r = 0; r < rounds; r++) {
    if (p.length < 3) return p;
    const out = [p[0]];
    for (let i = 0; i < p.length - 1; i++) {
      const [a, b] = [p[i], p[i + 1]];
      out.push([0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]], [0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]]);
    }
    out.push(p[p.length - 1]);
    p = out;
  }
  return p;
}

// Lay out in em units (1 = font size), y down, baseline at 0.
const strokes = [];
let x = 0;
for (const ch of word) {
  const g = glyphs.get(ch);
  if (!g) throw new Error(`glyph missing: ${ch}`);
  for (const s of g.strokes) strokes.push(chaikin(s.map(([gx, gy]) => [(x + gx) / unitsPerEm, -gy / unitsPerEm]), 3));
  x += g.adv;
}
let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
for (const s of strokes) for (const [px, py] of s) {
  x0 = Math.min(x0, px); x1 = Math.max(x1, px); y0 = Math.min(y0, py); y1 = Math.max(y1, py);
}
// Normalise to a box starting at (0,0); the boot script scales to fit.
const q = (v) => Math.round(v * 1e4) / 1e4;
const data = strokes.map((s) => s.flatMap(([px, py]) => [q(px - x0), q(py - y0)]));
const out = `// Generated by scripts/gen-boot-wordmark.mjs from EMS Allure (SIL OFL 1.1,
// Sheldon B. Michaels; SVG conversion Windell H. Oskay). Do not edit.
window.__aerialWordmark = { word: ${JSON.stringify(word)}, w: ${q(x1 - x0)}, h: ${q(y1 - y0)}, strokes: ${JSON.stringify(data)} };
`;
writeFileSync(join(root, 'public/boot-wordmark.js'), out);
console.info(`wrote public/boot-wordmark.js: ${strokes.length} strokes, ${data.reduce((n, s) => n + s.length / 2, 0)} points, ${out.length} bytes`);
